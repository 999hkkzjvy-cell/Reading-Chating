首先，这场看玉，是通灵宝玉第一次外形介绍的文字，从形、色、质、文四个方面全面地把通灵宝玉的奇特描写了一遍。并且点明，这就是那块补天石的幻相，区区一个幻相，却被贾府上下众人视作命根珍宝，不得不说讽刺感拉满。
而后将通灵宝玉身上的文字做了介绍，这里我们要注意到，为什么说薛宝钗的金锁和宝玉的不是一对，或者说不是薛姨妈等人可以打造出来配对的呢？从通灵宝玉的文字可见一斑。
通灵宝玉正面供十二个字，我们一直说“莫失莫忘，仙寿恒昌”，却忘记了，在这块玉石上，是把名字也写在上面的，“通灵宝玉”四个字不是贾府起的名字，是人家自己带的；反面是“一除邪祟，二疗冤疾，三知祸福”，一除邪祟后文会有具体情节，但是二疗冤疾和三知祸福，很明显，这块石头没有显出这个作用来，在第二十五回有一句批语，“通灵玉除邪，全部百回只此一见，何得再言？僧道踪迹虚实，幻笔幻想，写幻人于幻文也。”也就是说，写这句批语的人是读过完整的百回红楼的，他说通灵宝玉除邪祟只出现过一回，全书都是虚幻之笔，大家不要较真。当然我们可以认为，除邪祟只出现过一次，但是疗冤疾和知祸福还有出现的可能。但是在前八十回中，通灵宝玉确实再没有发挥过神通，或许在散轶的文字中，还有它知祸福的情节，但是知祸福也不能避免贾府的倾覆，或许石头虽然知祸福，但却无人能解它的警告，更加显示出它是幻相的无力感。
