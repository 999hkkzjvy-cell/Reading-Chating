大家早上好，愉快的周二就从读红楼梦开始吧！

今天我们阅读的第一回，可以说是红楼梦全书开宗明义的一回，不仅点明了整部书是作者经历一番梦幻之后，将真事隐去，撰写而成。更直接地告诉读者，此书写作不为其他，仅仅为了“使闺阁昭传”，并且特别提示到，要注意“梦”“幻”二字。

第一回看似复杂，其实只讲了两件事，其一是红楼梦也就是石头记的来历，其二便是甄士隐由盛转衰，凄惨度日，最后遁入空门的一生。
第一回涉及的人物不多，但却是整部书中具有关键线索性质的人物，抛开石头不提，一僧一道算是引发补天石凡心，乃至带其入红尘历练的主要推手。大家要注意，后文中每每遇到关键情节，总会明写或暗写这一僧一道，大家可以略略记录一下，看看他们到底都起了什么作用。
文章开篇讲在大荒山无稽崖青埂峰下有一块女娲补天剩下的顽石，关于女娲补天神话，大家都很熟悉了，补天石经过炼化，都是灵石，而多出来的这块灵石，往往象征着空有能力却无用之人。其实女娲炼就顽石三万六千五百零一块，到最后剩下哪块是随机的，但偏偏剩下的是一块多思多想的石头，且心思活泛不甘沉沦，这才有了跟随僧道入世的可能。
小小思考题：石头向僧道提出想到富贵场温柔乡中受享几年，按道理，僧道应该将它化为人形，或者其他生命体，否则一块石头，就算变为美玉，也只有供人把玩的份，哪听说过石头享受人生的？所以，为什么一僧一道要将石头变作美玉而非美人呢？

另外就是甄士隐和贾雨村这一对人物，其实甄士隐的故事很好概括，地方望族，妻子贤惠，女儿娇贵，结识并资助了一个穷书生，接下来是女儿被拐，夫妻神伤，家产因意外被燃烧殆尽，投奔岳父又被欺诈，最后经道人点化，出家去了。
很简单的故事，为什么要写一个这样的故事，又为什么要设置甄士隐这样一个人物？仅仅是为了带出英莲和贾雨村么？这是一方面的作用，但实际上，纵观甄士隐的一生，不难发现，他的经历其实是荣国府败落的一个小前奏，将烈火烹油一般的荣国府加水稀释，摘去几个人物，减掉一些情节，其实就是甄士隐的家庭，所以，甄士隐的出家，就已经预示着最终的结局，而英莲的出身和遭遇，也开启了金陵十二钗的悲声。
同时，甄士隐的存在，也是曹雪芹笔力的一个体现，正如脂批所言，“若从头逐个写去，成何文字？”一般涉及人物众多、情节奇幻的小说，都会面临一个难题，就是怎么才能合理安排前情背景，怎样能够使结构精巧而不至于内容泛滥或疏漏。甄士隐这个人物，正是曹雪芹为了将背景透露一二而设置的。一僧一道携了石头将往何处去，在上一节中是戛然而止，却又在甄士隐的梦中接续上，但又没有将背景彻底讲透，明确到底有多少人物涉及其中，梦醒之时文章又另起一新段落，可见曹雪芹在情节铺陈上，是刻意营造了一种幽而不透的氛围，算是一种我们说“设置悬念”的方法。

