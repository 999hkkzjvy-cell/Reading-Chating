在我看来，林黛玉杀敌只能是网络段子了，一方面，这和人设出入太大，不大可能在后面的情节出现如此大的转折，另一方面，咏絮才已经成为称赞才女的固定用法，强调的就是才华，并没有隐含背后谢道韫的其他事迹，在这一点上，似乎是有些牵强附会了。
