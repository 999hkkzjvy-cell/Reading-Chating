而后又自甄士隐引出贾雨村登场，中秋夜贾雨村有一联，历来是争论的焦点，“玉在匮中求善价，钗于奁内待时飞”，批语说“前用二玉合传，今用二宝合传，自是书中正眼。”也就是说，这句联是写宝玉和宝钗的。因为贾雨村字时飞，就有人简单地解释成薛宝钗等的是贾雨村，这就单纯是从字面理解了。在我看来，前半句说贾宝玉这块美玉待价而沽，等待的是识货的人，但纵观全书，除了林黛玉，有人认为贾宝玉是块美玉么？没有。因此，这世上并没有识货之人，贾宝玉终其一生也只能做一块籍籍无名的玉石。而薛宝钗是一个有计划有想法的人，在某种程度上，她和贾雨村是有相似之处的，这并不是说他们人品类似，而是他们都很会审时度势，同时擅长利用外界助力来实现自身目的。这是一种很难得的能力，只是要看被谁使用而已。
