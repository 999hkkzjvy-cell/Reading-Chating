第三回首先题目就出现了版本差异，己、庚、杨本作“贾雨村夤缘复旧职 林黛玉抛父进京都”，蒙、戚、列、舒、甲辰本作“托内兄如海酬训教 接外孙贾母惜孤女”。而我列出的回目则是甲戌本的题法“金陵城起复贾雨村 荣国府收养林黛玉”，在题目这里，甲戌本有一条批语标在“收养”二字旁，为“二字触目凄凉之至！”
咱们先来看看这三条回目的不同之处，首先，甲戌本的题目较为明了，只不过这里可能会有人认为：林如海还在世，为何荣府会和林黛玉形成收养关系？
其实“收养”这个词有收容抚养之意，而收容则有救助、收留的含义，因此收养在这里是一个比较凄凉的用法，是较为贴合林黛玉丧母之后无人教养的境地的。
而己、庚、杨本因为版本较早，存在曹雪芹修改回目或者传抄者修改回目的可能。“贾雨村夤缘复旧职”这半句倒没什么问题，重点在“林黛玉抛父进京都”，这个“抛”字很值得玩味，“抛”有抛弃、抛却之意，用在这里，林黛玉进京一事就似乎不是她不情不愿，反而有种主动之感，因为正文中有黛玉“不忍弃父而往”之语，虽然“弃”字也有抛弃之意，但更多的还是丢下，放弃之意，相比“抛”这个字，“弃”反而有种不得已之感。
因此抛父进京都，我个人认为不是特别恰当。
至于蒙本等所作的“托内兄如海酬训教 接外孙贾母惜孤女，在我看来是不太高明的改动，前半句贾雨村得起复的得意之感没有写出来，后半句则将人伦相聚作为重点内容，林黛玉被放置在次要地位，都不太符合正文想要表达的含义，因此不做展开讨论。
 
回目说完，咱们来看正文，前面贾雨村拜托林如海一事，群里已经有了讨论，这段也比较好理解，咱们就轻轻带过。 
着重说说林黛玉进贾府的内容。 
在这里需要大家注意一个细节，林黛玉临走时，“身体大愈”，大概是说，她现在处于一个相对健康的阶段，否则不会用“大愈”形容，在全书中多次出现“大愈”，基本上都是表示病好得差不多了的意思。但我们都知道林妹妹是多愁多病身，进了贾府就几乎没有过大愈的时候，那么这一点，也恰好说明，林黛玉自进贾府之后，方才开始了多病多泪的一生，如果真是这样，那么绛珠仙子还泪报恩，必得入贾府，那会不会贾敏的离世，林如海的亲缘单薄，都是为了林黛玉入贾府而设计的必要条件呢？

接下来的内容，就是作者通过林黛玉的眼睛，向读者详细展示荣府的繁华与气派。 
可以说林黛玉见贾母那一场，是一场非常出众的群像戏，在这一场次中，不仅主要人物大半登场，长辈有贾母、邢夫人、王夫人，平辈的李纨、春字三姐妹也各有笔墨，最不甘人后的王熙凤，出场更是隆重。而且通过人物对话，也将宝黛二人的基本情况和外貌特征终于呈现在读者面前，可以说信息量非常大了。
当众人询问黛玉病情时，黛玉的回答很有意思：“自来是如此”，她这病是胎里带的。大家可以想想，还有谁是胎里带的，贾宝玉是胎里带通灵宝玉，薛宝钗是胎里带一股热毒，这三个主人公都 从胎里带了些东西出来。且带出病症之后，黛玉和宝钗都有一个和尚来送解决之法，只不过一个是要黛玉出家，一个是真的给了药方。 
我们前面提到，一定要注意文中出现的癞头和尚、秃头和尚、疯癫道人等形象，大概率都是茫茫大士、渺渺真人出现来点化众人的。因此黛玉所遇癞头和尚，如同前面甄英莲一样，都是要她直接出家，提前结束尘缘。而黛玉也和英莲一样，都是被父母拒绝了脱离苦海的机会。而癞头和尚接下来的方法，更是直接指明了“泪尽而亡”的结局，不哭，不见外人（也就是贾宝玉），方可平安一世，只可惜这方法和绛珠的本愿违背，根本不可能实现。
 
接下来就是最知名的熙凤登场，众星拱月咋咋呼呼，不知道的以为是来打群架的。其实，林黛玉从上岸，消息就已经传回府内，否则贾母等一干人不会已经等在一起了，而三姐妹因为未得长辈允许，不能迎接远客（写到这里，突然想到贾母将黛玉唤作“远客”，听在黛玉耳中，不免又会伤心），所以不叫不来。但王熙凤不可能来迟，除非她自己想要来迟。 
那么，王熙凤为什么要来迟？结合王熙凤出场时的装扮，很明显她是经过了一番打扮（虽然审美一般也就是了，这个配色，怎么想也不会太好看），黛玉母亲初丧，作为晚辈，哪怕出于客气，王熙凤也不应该如此光彩照人，可她还是选择了这样一身辉煌夺目的装扮，这从声气上就压了一头，她为什么要如此？可能有人会认为，这是主人看重客人才盛装出席啊，但我们细想一下，黛玉远道而来，舟车劳顿，还未来得及梳洗，整个会面，会是一种衣袂飘香步步生莲的大型比美现场么？一般来说，都是主人好整以暇，客人盛装出席，才有以示尊重的意味。哪有已然主场优势的人还要再在服饰上声势浩大的呢，这不是示威很难解释啊。 
那么王熙凤为什么要示威？比较表面的解释是，大概是她知道林黛玉这一来就是长住，她要在第一时间让林黛玉知道，谁才是这个家真正管事的人。而我还有一个比较脑洞的解释，也许，这是林黛玉会嫁给贾宝玉的第一个证据。 
王熙凤是贾母身边得力之人，会是贾母心思的第一掌握者，也许，贾母此次接林黛玉入贾府，就是为了预备给宝玉说亲，那么一旦黛玉成为宝二奶奶，自然也就成了荣国府名正言顺的掌家媳妇，黛玉天资聪颖，贾府中人应该了解，那么，会和谁形成有力的竞争呢？当然是话事人王熙凤了，李纨虽然是大奶奶，但已经守寡，性子又软，正是因为她支棱不起来，王熙凤才过来给王夫人当帮手，而凤姐也明白，真正的权柄在贾政这支，那么，一旦林黛玉入局，王熙凤就再没有留在二房这边的理由了。所以初见时熙凤看似客套，实际处处彰显办事和管家能力的行为，似乎就有了解释。 

接下来是黛玉见两个舅舅的场景，从黛玉去见贾赦的路线来看，此时贾赦和贾政已经分家，贾母跟随贾政居住，结合后文，可见贾母确实偏心贾政，但同时也可看出贾政才是荣国府真正的掌管者，一方面，贾赦虽然袭爵，却只有爵位没有职位，而贾政是正经的工部员外郎，是有实权的，这也是为什么荣国府现在实际是二房当家。 
和王夫人说话时，王夫人向林黛玉介绍了贾宝玉，这里王夫人就有一个很微妙的态度，她大概率是不太接受林黛玉做儿媳预备役的，因此早早打下预防针，尽量避免二玉长时间相处。其实我们看王夫人的话，结合后文，就知道王夫人是在夸张，“混世魔王”四个字，形容宝玉其实是有些过了，这大概就是出于不想让黛玉对他有好印象的目的吧。 

下面一场便是二玉相见，这是一场非常高明的视角转换，先由黛玉心中所想写起，再到目之所见宝玉样貌，再写回内心熟悉之惑；而后便是宝玉眼中心中的黛玉，视角在两人之间转换，便将初见时惊喜吸引的情感体现得淋漓尽致。这也就给后面宝玉摔玉一节铺垫了情绪。 
等安置黛玉时，出现了给丫鬟的情节，我们计算年龄，此时黛玉应为六岁，贾宝玉七岁，雪雁十岁，贾母尚嫌她一团孩气，把鹦哥给了黛玉，说明鹦哥至少也在十几岁，而贾宝玉身边的袭人，也是贾母身边的丫鬟，也是因为她得力能干才给了宝玉，说明袭人最起码也和鹦哥差不多年龄，我们想一下，袭人大概年龄是宝玉的一倍还多，很难想象后文贾宝玉还是个不到十岁的小孩子，却和一个十几岁的大姑娘初试云雨情。由此我们可以大胆反推，实际上曹雪芹在写这一节时，大概是想把黛玉写成十几岁，至少要比雪雁大，这才有小孩无法照顾的困扰，而袭人比宝玉大不了几岁，初试云雨情时宝玉至少也是进入青春期，才有成事的可能。 

