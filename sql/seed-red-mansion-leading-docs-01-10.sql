领读文档
进入第四回，咱们需要稍稍剧透一点下一回的内容，以方便梳理一个时间线，那就是林黛玉入贾府的转天，王夫人便接到了来自金陵的信，告知薛蟠打死人命的事，也正是这一天，王夫人兄嫂派人来告诉，想把薛蟠叫进京来。

咱们暂且跳过贾雨村判案一说，单说薛蟠进京，即便是从金陵到京都，至多不会超过数月，再结合前文贾雨村游览山野风光时有“茂林修竹”之语，因此时间至早不会早于暮春，两相结合，薛宝钗入京应当与林黛玉入京差不多是同年。薛蟠出场时为15岁，宝钗比薛蟠小两岁，也就是13岁，到此，宝黛钗三人的年龄在这里就出现了一个比较不太令人接受的情况，即黛玉6岁，宝玉7、8岁，宝钗13岁。
其实宝钗的年龄在这里是比较合适的，较为理想的年龄差应是宝玉11-12岁，黛玉10-11岁，但如果放到全书来看，以这样的年龄，基本上过不了一两年，宝黛钗三人就进入男女大防的阶段，故事也就无法推进了，恐怕基于此种考虑，曹雪芹将林黛玉和贾宝玉的年龄改小了，但宝钗的年龄，不知道是疏忽了，还是一旦改小又和入宫待选契合不上，因此留下了一个漏洞。

说回正文，开头便留笔在李纨身上，算是一边夹杂着介绍人物，一边令黛玉进府一事做一小结。在这里对李纨的介绍比较有意思，书中说她“竟如槁木死灰一般”，这里我们可以想这样一个问题，为什么李纨会如槁木死灰一般。一方面肯定是因她年轻守寡，且看起来当年和贾珠夫妻应是相当恩爱，贾珠去世，她大受其伤，心如死灰是有可能的。另一方面，我们要知道，李纨的父亲曾是国子监祭酒，这个“曾”字很有意思，说明现在不是了，而且也不会是升官，否则一定会介绍其父现在的官位，那要么是李纨的父亲去世了，要么是被贬官或者罢官了。李纨本来是名宦之女，甚至李纨父亲的官位是高于贾政的，但一旦父亲去世或者贬官，李纨在婆家的地位肯定是不如从前，而她膝下还有一个贾兰，是绝对的嫡长孙。我们试想一下，李纨住在贾府，没有丈夫依靠，没有娘家撑腰，身边只有一个贾兰，天天眼看着赵姨娘明里暗里的算计宝玉，她的日子会好过么，她能不提心吊胆么？王熙凤如此泼辣，丈夫还在，尚有那色胆包天的贾瑞过来占便宜，更不要说形单影只的李纨了，因此所谓的槁木死灰，所谓的“大菩萨”的外号，不过是她自保的手段罢了。
这里还有一个小细节请大家注意，冷子兴演说荣国府时，说贾珠不到二十，娶妻生子之后，一病死了。而在本回中，却说“珠虽夭亡”，我们知道，“夭亡”这个词是有明确的使用限制的，即未成年早死，可是贾珠已经成年且成家了，在这里形容他的去世用了和冷子兴不同的“夭亡”，就很有令人遐想的空间，会不会是贾珠的死另有真相呢？

葫芦僧乱判葫芦案的内容咱们都很熟悉了，就选择几个我觉得比较有意思的点说一说。首先就是这个护官符，文中有一句话叫“石头亦曾照样抄写一张”，我们知道，红楼梦的写作视角，用今天的话来说叫“上帝视角”，虽然开篇就说本书是石头经历了一番尘世之后记录而成，但石头不在，也就是贾宝玉不在的地方，石头是看不到听不到，自然也不会记得住。我们可以认为，古人不清楚写作视角这种说法，因此不会刻意的注意视角问题，但红楼梦进入第二回后，全书只有此处石头亮明身份，后面再没有提过“石头”，为何偏偏在此特意提到石头抄写一张？抛开视角不论，要么是石头有大神通，可以神游云外，去到任何想去的地方，不过这种解释有些无趣；要么就是石头在别的地方见过护官符，也就是说，贾宝玉见过护官符，那么，他在什么情境下会见到护官符呢？不过，这不能作为贾宝玉考过功名做过官的证据哦，因为护官符是要给当官的人做个提醒，即便贾宝玉也得到一张护官符，应该也是写的他那个时代他需要注意的“贾史王薛”，不大可能把他的家世背景再告诉他本人一遍。
所以，根据护官符内容，应该是贾史王薛四大家族尚有权势的时候，有人把这个或有意或无意地给贾宝玉看过；还有一种可能，这护官符是一份证据，在四大家族败落被问罪时，贾宝玉作为受审人员之一，见过这份东西也说不定。

咱们来看护官符的内容，四大家族，贾、史、王都有官场中人，唯独薛家，现在是皇商，也就是说，薛家没有人在朝为官，只是经商。封建社会，是重农轻商的，那么薛家在这四大家族中，虽然钱财可能更多，但地位上却不见得能与其他三家相提并论。而且我们仔细分析这四句，好像有一种，其他三家更言其贵，而薛家则只言其富的感觉。

昨天群里有小伙伴提问，说这个时候出现的“王老爷”会不会是王子腾或者王熙凤的父亲。首先我认为不会是王子腾，因为前文提到，此时王子腾应在京中，后文也说王子腾升了九省统制，奉旨出京。如果是王熙凤的父亲，那么大家会不会觉得有一丝违和感，就是王家这么大的一个家族，薛蟠一个商人，打死人尚且混不在意，王家势力如此巨大，即便是要打点，有必要让王父亲自登门拜访么？
