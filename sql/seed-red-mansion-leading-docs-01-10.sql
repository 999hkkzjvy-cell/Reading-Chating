不知大家有没有注意到，宝黛的爱情到底是为什么发展得如此浓烈的？虽然是木石前盟，但那终究是前缘，到了今生，贾宝玉对林黛玉的感情，却不似我们认为的那样，是一上来就非卿不可，第五回以及接着的第六回，也是给我们提了个醒，木石前盟并没有因为前世的纠缠，而那么的板上钉钉，或者可以说，贾宝玉对林黛玉，是神瑛侍者对绛珠仙草的怜悯之心，而林黛玉还泪报恩，也是出自己方的“一厢情愿”，因此，他俩的感情存在着错位，至于这个“颗粒度”是什么时候因为什么对齐的，大家可以在后文找找答案。
