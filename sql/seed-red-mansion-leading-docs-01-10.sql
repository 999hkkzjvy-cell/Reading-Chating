而后文还有一处比较有趣的文字，说薛蟠的母亲王氏，“乃现任京营节度使王子腾之妹，与荣国府贾政的夫人王氏，是一母所生的姊妹”，这里这个说法很有趣，如果王子腾、王夫人、薛姨妈是一母所生，那这句话应该是“与现任京营节度使王子腾、荣国府贾政的夫人王氏是一母所生的姊妹”，但偏偏先强调是王子腾的妹妹，后才说和王夫人是一母所生，那么有没有可能，两人和王子腾不是一母所生，但薛蟠说王子腾是嫡亲的母舅，那么王子腾必然是嫡出，这个王夫人和薛姨妈的出身，就又有了两种猜测，第一，她俩的母亲是填房，两人也算嫡出；第二，她俩的母亲是妾室，她俩和王熙凤之父一样，都是庶出。如果是这样，会不会就能解释，为什么权势滔天的王家，会和一个商人，以及一个官位比自己低的人家联姻。
