最后再简单说说著名的《好了歌》，跛足道人的原文并不难理解，有趣的是甄士隐的解注，几乎句句都在说荣宁众人的结局，其中我认为比较有意思的两句，是“昨日黄土陇头送白骨，今宵红灯帐底卧鸳鸯”，批语为前半句“黛玉、晴雯一干人”，结合后文，明显这里指的是黛玉和晴雯是离世的结局。但是有意思的是，大家应该记得，晴雯临终前，是宝玉去见的她，算是送了她一程，那么，送林黛玉的又是谁？黄土陇头送白骨，很明显不是一个豪门贵族办白事应有的排场，这句话对应晴雯的死是很贴切的，那么，是不是预示着林黛玉离世时，贾府已经败落到无力支撑她身后事的地步了？而后半句的“今宵红灯帐底卧鸳鸯”，这里的批语是“一段妻妾迎新送死，倏恩倏爱，倏痛倏悲，缠绵不了”，这句究竟是指谁？一种理解是，林黛玉死后，贾宝玉马上娶了薛宝钗，这大概是高鹗整理的后四十回中“调包计”的来源，而我自己的理解，结合批语，既然是妻妾迎新送死，那么在这一干人中，涉及妻妾的主要人物只有王熙凤和平儿，我们知道在文中平儿是通房丫头，尚没有成为妾室，那么这半句会不会预示了王熙凤死后，平儿成为妾室，但恩爱转瞬即逝，悲痛突如其来的故事走向呢？

