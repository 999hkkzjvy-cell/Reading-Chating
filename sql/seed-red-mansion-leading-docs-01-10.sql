从太虚幻境出来的宝玉，经历了人生第一次梦遗，上回书有个小尾巴，和宝玉在太虚幻境共赴阳台的可卿，乳名兼美，兼的是钗黛之美，因此面容上不会和秦可卿有相似之处，也就是说，和贾宝玉云雨的其实也是个“假”可卿，或者说，是故意幻化出钗黛面容的可卿。但是为什么非要用“可卿”这个名字呢？而且这个可卿并不是所谓的秦可卿生魂，因为秦可卿此时正在门外看猫狗打架，并没有入梦，因此我们其实可以这样理解，那就是秦可卿是“情天情海幻情身”，是“主淫”的，因此在太虚幻境和宝玉相配的人也叫可卿，实际上是加强了秦可卿“淫”这一人物特质的。
等贾宝玉回到现实，有趣的是，他记得梦中所有一切事物，唯独不记得可卿的样貌了，不然，在见到薛宝钗和林黛玉时，一点不自然都没有，再次点出太虚幻境整体都是一个“幻”字。

至于和袭人一番云雨，可能有的小伙伴会觉得接受不了，尤其是现代所谓“双洁”的要求，男主角怎么能把不纯洁了呢？首先，袭人身份决定了即便宝玉和她有过肌肤之亲，也完全不会影响宝玉和未来正室的关系，感觉古人在这方面分得非常清，就连林黛玉在知道袭人开始拿妾室的月钱时，都是来道喜而完全没有吃醋。所以在那个年代，妾室是奴才，不是伴侣这个范畴的，在这个层面上，宝玉甚至可以说是纯洁的。另外，前面提过，宝玉此时尚未对黛玉产生浓烈的爱情，这里也提到他是喜欢袭人好看又温柔的，所以宝玉自己也并不认为这样做会对不起谁。
不过，在此处可以对宝玉的年龄做一个简单的猜测，根据他的生理反应，目前宝玉至小不会小于10岁，至大不会大于18岁，但是根据他哥哥贾珠的成婚年龄推断，如果宝玉这时候已经超过14岁，一方面，秦可卿不会有“他才多大”之语，而袭人也不会对梦遗这事这么震惊，因此推断此时宝玉年龄在10-13岁之间，那么也就是说，其实林黛玉到了贾府至少已经两年了，他俩还是处于两小无猜阶段。

接下来红楼梦第一喜剧演员刘姥姥登场，不得不说，刘姥姥劝女婿的一番话，很有些巾帼英雄的意思，顺境不张扬，逆境不气馁，面对机遇敢想敢干，有勇有谋。关键是她消息还很灵通，连狗儿自己都不见得知道的前尘往事，刘姥姥一个外姓人打听得清清楚楚，或许就因着这层脆弱的关系，刘姥姥才将女儿嫁给狗儿也未可知。不仅如此，她一个庄户人家，还知道王府现在升了边任，可见她随时都在关注王家的动向，这种心思不可谓不深。
同时升了边任这句话也可以略略解释关于王熙凤之父的身份，知道有狗儿这门穷亲戚的，只有王夫人的爹，王熙凤的爹，以及王夫人本人，现在王父已死，京中只有王夫人还认得这门亲，那么升了边任的就只能是王熙凤的爹了。但是前文又提到，是王子腾外派出京，所以这里就有两个解释：一是王熙凤的父亲不是才出京的，是早就出京了，那么他也可能有官职在身，当然官场黑话有的时候贬官也会名为“升迁”，在这里就不展开了；第二种解释就是，这是曹雪芹的一个笔误，也许最开始他是想把王熙凤安排成是王子腾的女儿，但后来进行了改动，而此处是他忘记修改的地方。
这一段和狗儿的对话其实非常有意思，刘姥姥消息如此灵通，自己本来也去过王家，也见过王夫人，而且根据后文，她和周瑞家的也认见过，但她偏偏要先示弱，引得狗儿说出与周瑞家的关系，而后又当仁不让地说女婿也去不得女儿也去不得只能她自己去，既全了女婿的面子，也彰显了自己的能力，说明自己住在女婿家不是吃白饭的，不能让女婿嫌弃自己是个累赘，就仅仅是进一趟城，便有这许多盘算，刘姥姥不可不谓智勇双全。

刘姥姥见到周瑞家的过程就不展开了，不过周瑞家的有一句话很有意思，她说“这里又比不得五年前了。如今太太竟不大管事了，都是琏二奶奶当家。”也就是说，五年前当家的还是王夫人，那么这期间究竟发生了什么，让王夫人放弃了，或者说表面放弃了当家的权力呢？会不会贾珠就是五年前去世的呢？
其实这里周瑞家的还有一个说法有点奇怪，她介绍凤姐时，说的是“当日大舅爷的女儿”，这个“当日”用的有点意思，感觉一般出现这个词，都是这个人已经不在了，要不然，直接说是“太太的内侄女，大舅爷的女儿”不是更通顺么，为什么要加“当日的”这几个字。不过结合第十回，王熙凤胞兄王仁带着家眷回南京，王熙凤给他准备要带给父母的礼物，说明此时王熙凤的父亲还在世，或许这也是曹雪芹反复纠结凤姐身世，多次修改留下的痕迹吧。

在这里我们可以稍微记下凤姐的年龄，最多不过20岁，如果我们把这一段故事和贾宝玉初试云雨情认为是同一时间段发生的，那么王熙凤最多比贾宝玉大10岁，最小大7岁，而贾珠活到现在应该是二十多岁，那么贾琏的这个琏二爷，就有意思了。贾府整体是无论荣宁，男女分开排行，惜春都不是荣国府的，也算四姑娘。所以贾珍是大哥哥，如果贾琏是琏二爷，那么贾琏就应该比贾珠大，贾宝玉就算老四。但这里面需要注意的是，看起来，其实参与排行的只有贾代善和贾代化的后代，其他次子没有参与到排行中，否则偌大一个贾家，就算男丁稀少，女孩断不会只有四个。
但是为什么贾宝玉也叫二爷，并且后文醉金刚、小红管贾芸也叫二爷，可见在贾府中，还有一套单论的排行，即亲近之人、宝贝宝玉之人、奉承宝玉之人，才管宝玉叫二爷，即把他和贾珠单论，这也是为什么会管贾珠叫珠大爷。大家可以留心，一般都是黛玉、宝玉房中的丫鬟还有茗烟叫宝玉为二爷。

说回正文，刘姥姥跟着周瑞家的来到贾府，先见的是平儿，在这里刘姥姥的态度也很值得玩味，她一上来以为平儿是凤姐，后来才知道“不过是个有些体面的丫头”，这“不过是个”四个字很有意思，刘姥姥家都穷成这样了，但确是正经的平民，面对卖身为奴的平儿，即便她再满身绫罗贵不可言，在身份上也是低刘姥姥一等的，因此刘姥姥对平儿的让座一点都不客气，直接就上炕了，这里并不是说姥姥不懂礼数，恰恰相反，她是太懂了。
等见凤姐这一场戏就更有意思了，刘姥姥进了凤姐的房间，那么大一个人进来，凤姐会不知道么，却故意不抬头，拿足了架子，但嘴上的客道却没少。就这一句，凤姐心机一览无余，首先，她不太清楚刘姥姥的来历，不知道该怎么对待刘姥姥，但很明显，绝不会是值得上心的富亲戚，只是即便是穷亲戚，也有不同的招待方式，但在刘姥姥面前，凤姐要把自己的身份站住，不能让人因为自己年龄小就轻视了自己。
而后的一番话简直是甩锅模板，不说自己高不可攀，却说对方厌弃自己。一面应付刘姥姥，一面派周瑞家的去王夫人处探口风，若不是有后文解释，都不知道这两句话在说什么。
后文夹写一段贾蓉来借东西，这段看似寻常，实际也是在敲打刘姥姥，尤其是凤姐叫了贾蓉回来又没什么事，只是说“我也没精神了”，一方面是让刘姥姥看清自己的权力，阖家上下都得听她的呼喝，另一方面也是暗戳戳告诉刘姥姥，有事快说，我累了。
所以接下来刘姥姥着急道明此次目的，才会把辈分弄乱，昨天沁沁在群里给狗儿家和王夫人家的辈分做了个梳理，刘姥姥和凤姐是一个辈分，也就是说狗儿是所谓王熙凤的侄子，板儿应该是侄孙，所以刘姥姥说带着“你侄儿”来，实际上是乱了辈分，在周瑞家的看来就是犯了大错。
我们再看这个时候凤姐一出手就给了刘姥姥二十两银子，从刘姥姥的反应来看，这二十两他家至少能用一年还带拐弯，贾府的财大气粗可见一斑，等刘姥姥二进大观园时，大家可以对比下那时给她的钱物，以及刘姥姥那次的表现和心态，是很有意思的。

这一回，其实总共写了三个女性使弄手段的内容，刘姥姥、周瑞家的以及凤姐，这三人都在不同的对象面前尽力显示自己的能力，刘姥姥是对女婿显摆，周瑞家的是对刘姥姥显摆，而凤姐不仅对刘姥姥，也对周瑞家的，周瑞家的是王夫人的陪嫁，但凤姐嘴上客气，一点没少使唤她，可见在凤姐眼里，她必须是言出法随的当家人。

